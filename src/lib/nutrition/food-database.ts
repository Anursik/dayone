export interface BuiltinFood {
  id: string;
  name: string;
  kcal: number;
  protein: number;
  fat: number;
  carbs: number;
  category: FoodCategory;
  source: "builtin";
}

export const BUILTIN_PREFIX = "b:";

export const BUILTIN_FOODS: BuiltinFood[] = ROWS.map(([id, name, kcal, protein, fat, carbs, category]) => ({
  id: BUILTIN_PREFIX + id,
  name,
  kcal,
  protein,
  fat,
  carbs,
  category,
  source: "builtin",
}));

const BY_ID = new Map(BUILTIN_FOODS.map((f) => [f.id, f]));

export function getBuiltinFood(id: string): BuiltinFood | undefined {
  return BY_ID.get(id);
}

export function isBuiltinFoodId(id: string): boolean {
  return id.startsWith(BUILTIN_PREFIX);
}
